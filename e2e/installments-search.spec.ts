import {test,expect} from '@playwright/test';

test('Ratenplan, Abbruch, Zahlung, Wiederholung und Wiederöffnung',async({page,request})=>{
 const day=new Date().toISOString().slice(0,10);
 const initial=await (await request.get('/api/state')).json();
 const accountResponse=await request.post('/api/state',{data:{op:'account',name:'Ratenkonto',type:'Girokonto',openingCents:100000}});
 expect(accountResponse.ok()).toBe(true);
 const account=(await accountResponse.json()).accounts.find((a:{name:string})=>a.name==='Ratenkonto');
 await page.goto('/#/installments');
 await expect(page.getByText('Mein persönlicher Bereich')).toHaveCount(0);
 await page.getByRole('button',{name:'Finanzierung hinzufügen'}).click();
 await page.getByLabel('Name',{exact:true}).fill('Meine langfristige Anschaffung');
 await page.getByLabel('Gesamtpreis inkl. Zinsen in EUR').fill('1000,01');
 await page.getByLabel('Monatsrate in EUR').fill('300');
 await page.getByRole('button',{name:'Abbrechen',exact:true}).click();
 expect((await (await request.get('/api/state')).json()).installments).toHaveLength(initial.installments.length);
 await page.getByRole('button',{name:'Finanzierung hinzufügen'}).click();
 await page.getByLabel('Name',{exact:true}).fill('Meine langfristige Anschaffung');
 await page.getByLabel('Gesamtpreis inkl. Zinsen in EUR').fill('1000,01');
 await page.getByLabel('Monatsrate in EUR').fill('0');
 await page.getByRole('button',{name:'Speichern',exact:true}).click();
 await expect(page.getByRole('alert')).toBeVisible();
 await expect(page.getByLabel('Name',{exact:true})).toHaveValue('Meine langfristige Anschaffung');
 await page.getByLabel('Monatsrate in EUR').fill('300');
 await page.getByRole('button',{name:'Speichern',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByRole('button',{name:/Meine langfristige Anschaffung/}).click();
 await expect(page.getByText('100,01', {exact:false}).first()).toBeVisible();
 await page.getByRole('button',{name:'Zahlung erfassen'}).first().click();
 await page.getByRole('combobox',{name:'Konto',exact:true}).selectOption(account.id);
 await page.getByRole('button',{name:'Buchen',exact:true}).click();
 await expect(page.getByText('Bezahlt · '+day)).toBeVisible();
 let state=await (await request.get('/api/state')).json();
 const plan=state.installments.find((p:{name:string})=>p.name==='Meine langfristige Anschaffung');
 const payload={op:'payInstallment',id:plan.id,index:1,accountId:account.id,date:day};
 expect((await request.post('/api/state',{data:payload})).ok()).toBe(true);
 state=await (await request.get('/api/state')).json();
 expect(state.transactions.filter((t:{installmentId:string})=>t.installmentId===plan.id)).toHaveLength(1);
 expect((await request.post('/api/state',{data:{...payload,index:999}})).status()).toBe(400);
 expect((await request.post('/api/state',{data:{op:'deleteInstallment',id:plan.id}})).status()).toBe(400);
 const payment=state.transactions.find((t:{installmentId:string})=>t.installmentId===plan.id);
 expect((await request.post('/api/state',{data:{op:'deleteTransaction',id:payment.id}})).ok()).toBe(true);
 await page.reload();await page.getByRole('button',{name:/Meine langfristige Anschaffung/}).click();await expect(page.getByRole('button',{name:'Zahlung erfassen'})).toHaveCount(4);
 await page.setViewportSize({width:320,height:568});
 expect(await page.evaluate(()=>document.body.scrollWidth<=innerWidth)).toBe(true);
});

test('ETF-Vorschläge füllen Symbol, Börse und Währung; Suchfehler erhält Eingabe',async({page})=>{
 await page.route('**/api/stocks/search?*',async route=>{
  const query=new URL(route.request().url()).searchParams.get('q');
  if(query==='Fehler')return route.fulfill({status:502,json:{error:'Suche nicht verfügbar'}});
  return route.fulfill({json:{results:[{name:'Persönlicher Welt ETF',symbol:'OWNETF',exchange:'XETRA',currency:'EUR',type:'ETF'}]}});
 });
 await page.goto('/#/stocks');
 await page.getByRole('button',{name:'Aktie hinzufügen',exact:true}).click();
 await page.getByLabel('Name',{exact:true}).fill('Fehler');
 await expect(page.getByRole('status')).toHaveText('Suche nicht verfügbar');
 await expect(page.getByLabel('Name',{exact:true})).toHaveValue('Fehler');
 await page.getByLabel('Name',{exact:true}).fill('Welt');
 await page.getByRole('button',{name:/Persönlicher Welt ETF/}).click();
 await expect(page.getByLabel('Symbol',{exact:true})).toHaveValue('OWNETF');
 await expect(page.getByLabel('Börse · optional')).toHaveValue('XETRA');
 await page.getByRole('button',{name:'Speichern',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Persönlicher Welt ETF',exact:true})).toBeVisible();
});

test('Darlehen: Sollzins, Zinsanteil, Rückzahlung und Persistenz',async({page,request})=>{
 await page.goto('/#/installments');
 await page.getByRole('button',{name:'Finanzierung hinzufügen'}).click();
 await page.getByRole('combobox',{name:'Art',exact:true}).selectOption('loan');
 await page.getByLabel('Name',{exact:true}).fill('Mein persönliches Darlehen');
 await page.getByLabel('Darlehensbetrag in EUR').fill('1000');
 await page.getByLabel('Fester Sollzins in % pro Jahr').fill('12');
 await page.getByLabel('Laufzeit in Monaten').fill('2');
 await page.getByLabel('Erste Fälligkeit').fill('2026-01-31');
 await page.getByRole('button',{name:'Speichern',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByRole('button',{name:/Mein persönliches Darlehen/}).click();
 await expect(page.getByRole('columnheader',{name:'Zinsen',exact:true})).toBeVisible();
 const state=await (await request.get('/api/state')).json();
 const loan=state.installments.find((p:{name:string})=>p.name==='Mein persönliches Darlehen');
 expect(loan.totalCents).toBe(101502);expect(loan.rateCents).toBe(50751);expect(loan.interestBps).toBe(1200);
 expect(state.transactions.filter((t:{installmentId:string})=>t.installmentId===loan.id)).toHaveLength(0);
 const account=state.accounts.find((a:{archived:boolean})=>!a.archived);
 expect((await request.post('/api/state',{data:{op:'payInstallment',id:loan.id,index:1,accountId:account.id,date:'2026-01-31'}})).ok()).toBe(true);
 await page.reload();await page.getByRole('button',{name:/Mein persönliches Darlehen/}).click();
 await expect(page.getByText('502,49', {exact:false}).first()).toBeVisible();
 await page.setViewportSize({width:320,height:568});
 await page.evaluate(()=>document.documentElement.style.fontSize='200%');
 expect(await page.evaluate(()=>document.body.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'build/loan-mobile.png',fullPage:true});
});
